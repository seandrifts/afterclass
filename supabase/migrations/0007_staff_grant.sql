-- ----------------------------------------------------------------
-- 店員送獎項的面額上限
-- ----------------------------------------------------------------
--
-- 店員原本只能發動隨機抽，期望成本三塊多。開放「指定獎項送出」之後，
-- 沒有上限的話等於每個店員都能隨意送出免單（面額 150），濫用的天花板
-- 差了四十倍。
--
-- 這個數字是老闆可調的：辦活動要送大獎時調高，活動結束再調回來。
-- 設成 0 等於完全不讓店員送；設成很大的數字等於不設限。
--
-- 預設 50 剛好涵蓋實物小獎與回饋金 50，但擋住免單。
--
-- 老闆自己在後台送不受這個限制。

alter table settings
  add column if not exists staff_grant_max_value int not null default 50
    check (staff_grant_max_value >= 0);

comment on column settings.staff_grant_max_value is
  '店員在店員端可送出的獎項面額上限。0 = 不開放，老闆在後台送不受限';
