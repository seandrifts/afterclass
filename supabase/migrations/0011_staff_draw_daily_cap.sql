-- ----------------------------------------------------------------
-- 店員代抽：每位會員每天的次數上限
-- ----------------------------------------------------------------
--
-- iPad 代抽沒有跟「這次有沒有消費」綁在一起，同一位客人被重複掃碼
-- 就能再抽一次。原本只靠「這位客人剛抽過」的警告讓店員自己判斷，
-- 擋不住手滑，也擋不住放水。
--
-- 這個數字是老闆可調的。0 = 不限制（預設，行為跟以前一樣）。
-- 只算店員發動的抽獎（iPad 代抽、店員發的動態 QR），客人自己掃紙卡
-- 不算，送獎項也不算。老闆自己操作不受這個限制。

alter table settings
  add column if not exists max_staff_draws_per_day int not null default 0
    check (max_staff_draws_per_day >= 0);

comment on column settings.max_staff_draws_per_day is
  '店員每天可以幫同一位會員抽幾次。0 = 不限制，老闆操作不受限';
