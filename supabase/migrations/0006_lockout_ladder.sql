-- ================================================================
-- 遞增鎖定
--
-- 原本每次都固定鎖 15 分鐘，換算下來攻擊者每天仍可嘗試 480 次。
-- 6 位數 PIN 撐得住（平均 2.9 年），但 4 位數只要 10 天就會被猜中。
--
-- 改成每次被鎖時間翻倍：15 分鐘 → 1 小時 → 4 小時 → 24 小時。
-- 連續攻擊一天之後速率幾乎歸零，而正常店員打錯幾次頂多等 15 分鐘，
-- 且登入成功就把階梯歸零，不會被歷史紀錄拖累。
-- ================================================================

alter table staff
  add column if not exists lockout_level int not null default 0;

comment on column staff.lockout_level is
  '連續被鎖定的次數。決定下一次要鎖多久，登入成功後歸零';


-- ----------------------------------------------------------------
-- 現有帳號的 PIN 檢查
--
-- 這裡只提醒，不強制改。強制改會把老闆鎖在系統外面。
-- ----------------------------------------------------------------
do $$
declare
  v_count int;
begin
  select count(*) into v_count from staff where is_active;
  raise notice '目前有 % 個啟用中的帳號。新的最低長度為 6 位數，', v_count;
  raise notice '既有 PIN 不受影響，但建議避開全同數字與連號。';
end $$;
